"""rtros 的安装器：两个模式。

1. `--venv`（推荐）：在仓内 `out/venv` 建一个**免 pip** 的虚拟环境，把
   `scripts/src` 通过 `.pth` 挂进去（等价于 editable 安装），并生成 `rtros.cmd`
   启动器。这样不碰系统 site-packages，沙箱/受限环境也能用。
   之所以 `--without-pip`：本机 `ensurepip` 在受限环境里会因临时目录 ACL 失败。

2. 默认（无参数）：把 `scripts/` 以 editable 方式装进**当前解释器**（需要 pip，
   见下方两个理由）。用于普通开发机。

为什么默认模式不能直接 `pip install -e scripts`：

1. 受限环境里 `tempfile.mkdtemp()` 建出的目录本进程不可写，pip 的构建隔离会在
   创建临时目录后立刻失败；这里在 import pip 之前把 `mkdtemp` 换成 `os.makedirs`。
2. 统一加 `--no-build-isolation --no-deps`：本机已装 setuptools 与运行期依赖，
   不需要联网拉构建依赖。

用法：
    python tools/pyenv/install.py --venv        # 建/刷新仓内 venv 与 rtros 启动器
    python tools/pyenv/install.py --check-venv  # 只看仓内 venv 是否可用
    python tools/pyenv/install.py --check       # 看当前解释器是否装了 rtros
    python tools/pyenv/install.py               # editable 装进当前解释器
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TARGET = REPO / "scripts"
SRC = TARGET / "src"

VENV_DIR = REPO / "out" / "venv"
PTH_NAME = "rtros_dev.pth"
LAUNCHER = "rtros.cmd"


def _patch_tempfile() -> None:
    """把 mkdtemp 换成「用 os.makedirs 建的目录」，绕开受限环境的 ACL 问题。"""

    def mkdtemp(suffix: str = "", prefix: str = "tmp", dir: str | None = None) -> str:
        base = Path(dir) if dir else Path(tempfile.gettempdir())
        path = base / f"{prefix}{uuid.uuid4().hex[:8]}{suffix}"
        path.mkdir(parents=True, exist_ok=False)
        return str(path)

    tempfile.mkdtemp = mkdtemp  # type: ignore[assignment]
    tempfile.TemporaryDirectory._mkdtemp = staticmethod(mkdtemp)  # type: ignore[attr-defined]


def _run(argv: list[str], *, quiet: bool = False) -> int:
    if not quiet:
        print("$ " + " ".join(argv), flush=True)
    env = dict(os.environ)
    env.setdefault("PYTHONIOENCODING", "utf-8")
    return subprocess.call(argv, env=env, cwd=str(REPO))


def venv_python() -> Path:
    """仓内 venv 的解释器路径（Windows / POSIX 各一种布局）。"""
    candidate = VENV_DIR / "Scripts" / "python.exe"
    return candidate if candidate.exists() else VENV_DIR / "bin" / "python"


def venv_site_packages() -> Path:
    """仓内 venv 的 site-packages 目录。"""
    windows = VENV_DIR / "Lib" / "site-packages"
    if windows.is_dir():
        return windows
    return next((VENV_DIR / "lib").glob("python*/site-packages"))


def create_venv(quiet: bool = False) -> int:
    """建（或刷新）仓内 venv，并挂上 `scripts/src` + 生成 `rtros.cmd`。"""
    if not venv_python().exists():
        rc = _run(
            [
                sys.executable,
                "-m",
                "venv",
                "--without-pip",
                "--system-site-packages",
                str(VENV_DIR),
            ],
            quiet=quiet,
        )
        if rc != 0:
            print(f"[pyenv] 建 venv 失败（退出码 {rc}）：{VENV_DIR}")
            return rc

    site = venv_site_packages()
    site.mkdir(parents=True, exist_ok=True)
    pth = site / PTH_NAME
    pth.write_text(f"{SRC}\n", encoding="utf-8")

    launcher = venv_python().parent / LAUNCHER
    body = (
        "@echo off\r\n"
        "rem rtros launcher (repo-local venv), generated by tools/pyenv/install.py. Do not edit.\r\n"
        '"%~dp0python.exe" -m rtros %*\r\n'
    )
    launcher.write_bytes(body.encode("ascii"))

    if not quiet:
        print(f"[pyenv] venv   : {VENV_DIR}")
        print(f"[pyenv] .pth   : {pth}")
        print(f"[pyenv] 启动器 : {launcher}")
    return 0


def venv_version() -> str | None:
    """仓内 venv 里 `python -m rtros --version` 的输出；跑不起来返回 None。"""
    exe = venv_python()
    if not exe.exists():
        return None
    env = dict(os.environ)
    env.setdefault("PYTHONIOENCODING", "utf-8")
    proc = subprocess.run(  # noqa: S603 - 固定 argv，无用户输入
        [str(exe), "-m", "rtros", "--version"],
        cwd=str(REPO),
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    return proc.stdout.strip() if proc.returncode == 0 else None


def installed_version() -> str | None:
    """当前解释器里已安装的 rtros 版本；没装返回 None。"""
    try:
        import rtros
    except ImportError:
        return None
    return rtros.__version__


def install(quiet: bool = False) -> int:
    """以 editable 方式安装 `scripts/`（重复执行等于刷新）。

    走**进程内** pip（`pip._internal.cli.main`）而不是子进程：受限环境里子进程
    的 stdio 管道会被拦（表现为 pip 卡死），而进程内调用只碰文件系统。
    """
    _patch_tempfile()
    from pip._internal.cli.main import main as pip_main

    argv = [
        "install",
        "--no-build-isolation",
        "--no-deps",
        "--no-warn-script-location",
        "-e",
        str(TARGET),
    ]
    if not quiet:
        print("$ pip " + " ".join(argv), flush=True)
    return int(pip_main(argv) or 0)


def main(argv: list[str] | None = None) -> int:
    """入口：`--venv` 建仓内环境，默认装进当前解释器，`--check*` 只查询。"""
    parser = argparse.ArgumentParser(prog="pyenv-install.py", description="安装/检查 rtros")
    parser.add_argument("--venv", action="store_true", help="建/刷新仓内 out/venv 与 rtros 启动器")
    parser.add_argument("--check-venv", action="store_true", help="只检查仓内 venv 是否可用")
    parser.add_argument("--check", action="store_true", help="只检查当前解释器是否已装 rtros")
    parser.add_argument("--quiet", action="store_true", help="不打印执行中的命令")
    args = parser.parse_args(argv)

    if args.check_venv:
        version = venv_version()
        if version is None:
            print(f"[pyenv] 仓内 venv 不可用（{venv_python()}）；先跑 --venv")
            return 1
        print(f"[pyenv] 仓内 venv 可用：{version}")
        return 0

    if args.venv:
        code = create_venv(quiet=args.quiet)
        if code != 0:
            return code
        version = venv_version()
        if version is None:
            print("[pyenv] venv 建好了，但 `python -m rtros --version` 跑不起来")
            return 1
        print(f"[pyenv] 完成：{venv_python()} 里可用 `rtros`（{version}）")
        return 0

    version = installed_version()
    if args.check:
        if version is None:
            print("[pyenv] 未安装 rtros")
            return 1
        print(f"[pyenv] 已安装：rtros {version}")
        return 0

    code = install(quiet=args.quiet)
    if code != 0:
        print(f"[pyenv] 安装失败（pip 退出码 {code}）")
        return code
    version = installed_version()
    if version is None:
        print("[pyenv] 安装命令成功，但当前解释器仍 import 不到 rtros")
        return 1
    print(f"[pyenv] 安装完成：rtros {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
